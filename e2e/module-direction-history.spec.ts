import { expect, test } from '@playwright/test'

const source='/cases?traceId=2037904916466732346556&caseId=case-ppt-management&caseView=eval&timeRange=30d&environment=Production'

test('点击模块直接查看不同方向及完整历史，方向刷新和返回可恢复',async({page},testInfo)=>{
  await page.goto(source)
  await page.getByRole('button',{name:'查看 skill 进化历史',exact:true}).click()
  const detail=page.getByRole('dialog',{name:'skill · 进化详情',exact:true})
  const directions=detail.getByRole('combobox',{name:'进化方向',exact:true})
  await expect(directions).toBeVisible()
  await expect(detail.getByRole('button',{name:'skill sop错误',exact:true})).toHaveAttribute('aria-expanded','false')
  await expect(detail.getByRole('button',{name:'skill name/description错误',exact:true})).toHaveAttribute('aria-expanded','false')
  await expect(detail.locator('article[data-evolution-record-id]')).toHaveCount(0)
  const sop=await directions.locator('option').evaluateAll(nodes=>nodes.find(node=>node.textContent?.includes('skill sop错误'))?.getAttribute('value'))
  expect(sop).toBeTruthy()
  await directions.selectOption(sop!)
  await expect(page).toHaveURL(url=>url.searchParams.get('moduleEvolutionDirectionId')===sop)
  await expect(detail.getByRole('button',{name:'skill sop错误',exact:true})).toHaveAttribute('aria-expanded','false')
  await detail.getByRole('button',{name:'skill sop错误',exact:true}).click()
  await expect(detail).toContainText('evolution-module-path-demo-sop-agent')
  await expect(detail).toContainText('evolution-module-path-demo-sop-strategy')
  await expect(detail).toContainText('evolution-finding-module-path-demo-sop-history-undistributed')
  await expect(detail.locator('article[data-evolution-record-id="evolution-module-path-demo-sop-agent"]')).not.toContainText('品味库召回错误')
  const agent=detail.locator('[data-evolution-record-id="evolution-module-path-demo-sop-agent"]')
  await expect(agent.getByRole('list',{name:'完整流转历史',exact:true})).toContainText('问题 · 问题建立')
  await expect(agent.locator('details').filter({has:page.locator('summary',{hasText:'流转历史'})})).toHaveAttribute('open','')
  await expect(agent.getByText('纳入数据集',{exact:false}).first()).toBeVisible()
  await page.reload()
  await expect(directions).toHaveValue(sop!)
  await expect(detail.getByRole('button',{name:'skill sop错误',exact:true})).toHaveAttribute('aria-expanded','false')
  await detail.getByRole('button',{name:'skill sop错误',exact:true}).click()
  await agent.getByRole('link',{name:'查看进化数据集',exact:true}).click()
  await expect(page).toHaveURL(/datasets-evaluations/)
  await page.getByRole('button',{name:'返回来源页面',exact:true}).click()
  await expect(directions).toHaveValue(sop!)
  await expect(agent.getByRole('region',{name:'4 是否上线',exact:true})).toContainText('待发布')
  for(const width of [1280,1440]){
    await page.setViewportSize({width,height:900})
    await agent.getByRole('list',{name:'完整流转历史',exact:true}).scrollIntoViewIfNeeded()
    await page.screenshot({path:testInfo.outputPath(`module-direction-history-${width}.png`),animations:'disabled'})
  }
  await detail.getByRole('heading',{name:'skill评分依据',exact:true}).click()
  await expect(detail.getByText('skill 命中失败 Rubric，需要查看根证据。',{exact:true})).toBeVisible()
  await directions.selectOption('')
  await expect(detail).toContainText('品味库召回错误')
  await page.goBack()
  await expect(directions).toHaveValue(sop!)
})

test('模块行点击不打开Evidence，明确Evidence按钮仍可独立使用',async({page})=>{
  await page.goto(source)
  const row=page.getByRole('row').filter({has:page.getByRole('button',{name:'查看 记忆 进化历史',exact:true})})
  await row.locator('td').nth(3).click()
  await expect(page.getByRole('dialog',{name:'记忆 · 进化详情',exact:true})).toBeVisible()
  await page.getByRole('dialog',{name:'记忆 · 进化详情',exact:true}).getByRole('button',{name:'Close panel',exact:true}).click()
  await page.getByRole('button',{name:'查看 记忆 Evidence',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'记忆 Evidence',exact:true})).toBeVisible()
  await expect(page.getByRole('dialog',{name:'记忆 · 进化详情',exact:true})).toHaveCount(0)
})

test('关闭详情后恢复完整 Case / Trace 列表范围',async({page})=>{
  await page.goto('/cases?traceId=trace-ppt-generate&caseView=eval&timeRange=30d')
  const detail=page.getByRole('dialog',{name:/Case 详情/})
  await expect(detail).toBeVisible()
  await detail.getByRole('button',{name:'关闭 Case 详情',exact:true}).click()
  await expect(page).toHaveURL(url=>!url.searchParams.has('traceId') && url.searchParams.get('caseClosed')==='1')
  await expect(page.getByRole('table',{name:'Case / Trace 列表'}).getByRole('row')).toHaveCount(11)
})
