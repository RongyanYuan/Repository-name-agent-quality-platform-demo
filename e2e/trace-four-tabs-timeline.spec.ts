for(const width of [1280,1440])test(`${width}px 三Tab及归因折叠、评分操作无重叠`,async({page},testInfo)=>{
  await page.setViewportSize({width,height:900})
  await page.goto('/cases?traceId=trace-governance-demo-ppt&timeRange=30d')
  for(const tab of ['Session 对话','评测中心','产物评测']){
    await detail(page).getByRole('tab',{name:tab,exact:true}).click()
    await expect(detail(page).getByRole('tab',{name:tab,exact:true})).toHaveAttribute('aria-selected','true')
    const clips=await detail(page).locator('header h2,[role="tab"]').evaluateAll(nodes=>nodes.filter(node=>{const el=node as HTMLElement,r=el.getBoundingClientRect();return r.width>0 && (el.scrollWidth>el.clientWidth+1 || r.left<0 || r.right>innerWidth+1)}).map(node=>node.textContent))
    expect(clips).toEqual([])
    await page.screenshot({path:testInfo.outputPath(`${tab}-${width}.png`),animations:'disabled'})
  }
  await page.goto('/cases?traceId=trace-ppt-generate&caseView=eval&timeRange=30d')
  await detail(page).getByRole('button',{name:'查看 skill 进化历史',exact:true}).click()
  const module=page.getByRole('dialog',{name:'skill · 进化详情',exact:true})
  await expect(module.getByRole('button',{name:'skill sop错误',exact:true})).toHaveAttribute('aria-expanded','false')
  await page.screenshot({path:testInfo.outputPath(`directions-collapsed-${width}.png`),animations:'disabled'})
  await module.getByRole('button',{name:'skill sop错误',exact:true}).click()
  await expect(module.locator('[data-evolution-record-id="evolution-module-path-demo-sop-agent"]')).toBeVisible()
  await page.screenshot({path:testInfo.outputPath(`direction-expanded-${width}.png`),animations:'disabled'})
  await module.getByRole('button',{name:'Close panel',exact:true}).click()
  await page.goto('/cases?traceId=trace-governance-demo-ppt&caseView=outcome&timeRange=30d')
  await detail(page).getByRole('tab',{name:'产物评测',exact:true}).click()
  await detail(page).getByRole('row',{name:/^管理层风格匹配/}).getByRole('button',{name:'人工复核',exact:true}).click()
  await page.screenshot({path:testInfo.outputPath(`outcome-review-${width}.png`)})
  await page.keyboard.press('Escape')
  await expect(detail(page)).toBeVisible()
})
