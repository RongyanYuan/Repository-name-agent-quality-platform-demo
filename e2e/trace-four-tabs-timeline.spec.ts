import { expect, test, type Page } from '@playwright/test'

const detail=(page:Page)=>page.getByRole('dialog',{name:/Case 详情/})
const frozen=(page:Page)=>page.evaluate(()=>{const state=JSON.parse(localStorage.getItem('office-agent-evolution-governance:v1')!).state;return JSON.stringify({experiments:state.experiments,decisions:state.gateDecisions})})
test('Trace列表单一最新状态、三个Tab和模块内默认折叠',async({page})=>{
  await page.goto('/cases?traceId=trace-ppt-generate&timeRange=30d&caseClosed=1')
  const list=page.getByRole('table',{name:'Case / Trace 列表'})
  await expect(list.getByRole('columnheader',{name:'状态',exact:true})).toBeVisible()
  await expect(list.getByRole('columnheader',{name:'执行 / 模块复核'})).toHaveCount(0)
  await expect(list.getByRole('columnheader',{name:'治理去向 / 最近流转'})).toHaveCount(0)
  const latest=list.getByRole('button',{name:`查看 Trace 2037904916466732346556 最新状态`,exact:true})
  await expect(latest).toContainText(/准出|加入数据集|通过|已确认/)
  await latest.click()
  await expect(detail(page).getByRole('tab')).toHaveCount(3)
  await expect(detail(page).getByRole('tab',{name:'评测中心',exact:true})).toHaveAttribute('aria-selected','true')
  await expect(detail(page).getByRole('tab',{name:'治理链路',exact:true})).toHaveCount(0)
  await expect(detail(page).getByRole('tab',{name:'任务与关联'})).toHaveCount(0)
  await expect(detail(page).getByRole('tab',{name:'Trace 与 Evidence'})).toHaveCount(0)
  await expect(page.getByRole('region',{name:'治理时间分支图'})).toHaveCount(0)
  await detail(page).getByRole('button',{name:'查看 skill 进化历史',exact:true}).click()
  const module=page.getByRole('dialog',{name:'skill · 进化详情',exact:true})
  await expect(module.locator('[data-evolution-direction-id] button[aria-expanded="false"]')).not.toHaveCount(0)
  await expect(module.locator('article[data-evolution-record-id]')).toHaveCount(0)
})

test('过程评分去重、产物细项隔离、两次人工复核刷新与冻结保护',async({page})=>{
  await page.goto('/cases?traceId=trace-governance-demo-ppt&caseView=eval&timeRange=30d')
  const before=await frozen(page)
  await expect(detail(page).getByRole('heading',{name:'过程评测',exact:true})).toHaveCount(0)
  await expect(detail(page).getByRole('heading',{name:'产物 / 结果评测'})).toHaveCount(0)
  await expect(detail(page).getByRole('row',{name:/^Outcome/})).toHaveCount(0)
  await detail(page).getByRole('tab',{name:'产物评测',exact:true}).click()
  const select=page.getByLabel('选择评测产物',{exact:true})
  await expect(select.locator('option')).toHaveCount(2)
  const row=detail(page).getByRole('row',{name:/^管理层风格匹配/})
  await expect(row).toContainText('1.10 / 2')
  for(const [score,note] of [['0','浏览器产物第一次复核'],['1.25','浏览器产物第二次复核']] as const){
    await row.getByRole('button',{name:'人工复核',exact:true}).click()
    await page.getByLabel('产物人工分数（0–2）',{exact:true}).fill(score)
    await page.getByLabel('产物辅助结论',{exact:true}).selectOption('FAIL')
    await page.getByLabel('产物复核说明',{exact:true}).fill(note)
    await page.getByRole('button',{name:'保存产物复核',exact:true}).click()
    await expect(page.getByRole('region',{name:'产物细项人工复核'})).toHaveCount(0)
  }
  await page.reload()
  await expect(detail(page).getByRole('row',{name:/^管理层风格匹配/})).toContainText('1.25 / 2')
  await detail(page).getByRole('row',{name:/^管理层风格匹配/}).getByRole('button',{name:'评分依据',exact:true}).click()
  const evidence=page.getByRole('dialog',{name:'管理层风格匹配 · 评分依据'})
  await expect(evidence).toContainText('Rubric')
  await expect(evidence).toContainText('根证据')
  await evidence.getByRole('button',{name:'evidence-outcome-dimension-demo-artifact-governance-demo-ppt-2',exact:true}).click()
  await expect(page).toHaveURL(/caseView=outcome/)
  const root=page.getByRole('dialog',{name:/Evidence/})
  await expect(root).toContainText('1.10 / 2')
  await expect(root).toContainText('log-governance-demo-ppt')
  await page.keyboard.press('Escape')
  await expect(detail(page)).toBeVisible()
  await detail(page).getByRole('row',{name:/^管理层风格匹配/}).getByRole('button',{name:'评分依据',exact:true}).click()
  await evidence.getByText('复核历史（2 条）',{exact:true}).click()
  await expect(evidence).toContainText('浏览器产物第一次复核')
  await expect(evidence).toContainText('浏览器产物第二次复核')
  await evidence.getByRole('button',{name:'Close panel',exact:true}).click()
  await page.getByLabel('选择评测产物',{exact:true}).selectOption('artifact-outcome-dimension-demo-summary')
  await expect(detail(page)).not.toContainText('浏览器产物第二次复核')
  expect(await frozen(page)).toBe(before)
})

