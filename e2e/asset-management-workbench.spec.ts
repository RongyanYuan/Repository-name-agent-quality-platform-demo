import { promises as fs } from 'node:fs'
import { expect, test } from '@playwright/test'

test('资产管理主链路：全版本历史、来源隔离与实际报告曲线', async ({ page, context }) => {
  await page.goto('/assets-skills')
  const type = page.getByLabel('资产类型')
  await type.selectOption('TASTE_SKILL')
  const asset = page.getByLabel('具体资产')
  await asset.selectOption({ index: 1 })
  await expect(page.getByLabel('资产版本')).toBeEnabled()
  await page.getByLabel('资产版本').selectOption('__ALL_ASSET_VERSIONS__')
  await expect(page.getByLabel('资产版本')).toHaveValue('__ALL_ASSET_VERSIONS__')
  await page.getByLabel('资产开始时间').fill('2026-09-01T00:00')
  await page.getByLabel('资产结束时间').fill('2026-10-31T23:59')
  await expect(page.getByRole('table', { name: '资产版本表现' })).toBeVisible()
  const versionTable = page.getByRole('table', { name: '资产版本表现' })
  await expect(versionTable.getByRole('columnheader', { name: '当前状态' })).toBeVisible()
  await expect(versionTable.getByRole('row').filter({ has: page.getByRole('cell', { name: '0.9.0', exact: true }) })).toContainText('Production · 使用中')
  await expect(versionTable.getByRole('row').filter({ has: page.getByRole('cell', { name: '1.0.0-rc.1', exact: true }) })).toContainText('Staging · 验证中')
  await expect(page.getByRole('button', { name: '下载报告' })).toBeEnabled()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载报告' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toContain('asset-report-')
  const reportPath = await download.path()
  expect(reportPath).toBeTruthy()
  const report = await fs.readFile(reportPath!, 'utf8')
  expect(report).toContain('历史版本产物平均分')
  expect(report).toContain('时间')
  expect(report).toContain('评分（0–2）')
  expect(report).toContain('触发数据集')
  expect(report).toContain('资产版本')
  const reportPage = await context.newPage()
  await reportPage.setContent(report)
  await expect(reportPage.locator('polyline.chart-line')).toHaveCount(1)
  await expect(reportPage.locator('circle.chart-dot')).toHaveCount(3)
  await expect(reportPage.locator('.chart-version')).toHaveText(['0.9.0', '1.0.0-rc.1', '3.0'])
  const reportVersions = reportPage.getByRole('table', { name: '资产版本表现' })
  await expect(reportVersions.getByRole('columnheader', { name: '当前状态' })).toBeVisible()
  await expect(reportVersions.getByRole('row').filter({ has: reportPage.getByRole('cell', { name: '0.9.0', exact: true }) })).toContainText('Production · 使用中')
  await expect(reportVersions.getByRole('row').filter({ has: reportPage.getByRole('cell', { name: '1.0.0-rc.1', exact: true }) })).toContainText('Staging · 验证中')
  const history = reportPage.getByRole('table', { name: '资产进化历史' })
  await expect(history).toContainText('dataset-module-path-demo-taste')
  await expect(history).toContainText('dataset-workspace-taste-090-quality-attribution')
  await expect(history).toContainText('dataset-workspace-taste-100rc-recall-attribution')
  await expect(history).not.toContainText('dataset-module-path-demo-memory')
  await expect(history).not.toContainText('dataset-module-path-demo-1')
  await expect(history).not.toContainText('dataset-regression')
  await expect(history).not.toContainText('dataset-generalization')
  const link = history.locator('a[href*="dataset-module-path-demo-taste"]')
  const target = new URL(await link.getAttribute('href') ?? '')
  expect(target.searchParams.get('skill')).toBe('skill-taste-executive')
  expect(target.searchParams.get('skillVersion')).toBe('0.9.0')
  await expect(page).toHaveURL(url => url.searchParams.get('assetType') === 'TASTE_SKILL' && Boolean(url.searchParams.get('assetId')) && url.searchParams.get('assetVersion') === '__ALL_ASSET_VERSIONS__' && Boolean(url.searchParams.get('assetTimeFrom')))
  await reportPage.goto(target.href)
  await expect(reportPage.getByRole('heading', { name: /数据集详情.*品味召回/ })).toBeVisible()
  await expect(reportPage.getByLabel('Skill 版本')).toHaveValue('0.9.0')
})

test('分类全部资产：标题去重、完整列表、历史曲线与有效报告资产链接', async ({ page, context }) => {
  await page.goto('/assets-skills?assetType=PRODUCTION_SKILL&assetVersion=__ALL_ASSET_VERSIONS__&assetTimeFrom=2026-08-01T00:00&assetTimeTo=2026-10-31T23:59')
  await expect(page.getByRole('heading', { name: '资产管理', exact: true })).toHaveCount(1)
  await expect(page.getByLabel('资产版本')).toBeDisabled()
  await expect(page).toHaveURL(url => !url.searchParams.has('assetVersion'))
  const table = page.getByRole('table', { name: '分类资产表现' })
  await expect(table.getByRole('row')).toHaveCount(5)
  for (const name of ['PPT Builder', 'Spreadsheet Analyst', 'Word Builder', 'Canvas Builder']) {
    await expect(table.getByRole('link', { name, exact: true })).toBeVisible()
  }
  const metrics = page.getByRole('region', { name: '类别总览指标' })
  for (const label of ['资产数', '产物平均分', '已评测产物', '进化项数', '贡献 Trace']) await expect(metrics.getByText(label, { exact: true })).toBeVisible()
  const chart = page.getByRole('img', { name: '类别产物平均分历史' })
  await expect(chart).toContainText('时间')
  await expect(chart).toContainText('评分（0–2）')
  expect(await chart.locator('.chart-value').count()).toBeGreaterThan(1)

  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载报告' }).click()
  const download = await downloadPromise
  const reportPath = await download.path()
  expect(reportPath).toBeTruthy()
  const report = await fs.readFile(reportPath!, 'utf8')
  const reportPage = await context.newPage()
  await reportPage.setContent(report)
  const reportTable = reportPage.getByRole('table', { name: '分类资产表现' })
  await expect(reportTable.getByRole('row')).toHaveCount(5)
  await expect(reportPage.getByRole('img', { name: '类别产物平均分历史' })).toBeVisible()
  await expect(reportPage.locator('.chart-value')).toHaveText(await chart.locator('.chart-value').allTextContents())
  for (const name of ['PPT Builder', 'Spreadsheet Analyst', 'Word Builder', 'Canvas Builder']) {
    const pageRow = table.getByRole('row').filter({ has: page.getByRole('link', { name, exact: true }) })
    const reportRow = reportTable.getByRole('row').filter({ has: reportPage.getByRole('link', { name, exact: true }) })
    await expect(reportRow.getByRole('cell')).toHaveText(await pageRow.getByRole('cell').allTextContents())
  }
  const assetLink = reportTable.getByRole('link', { name: 'PPT Builder', exact: true })
  const target = new URL(await assetLink.getAttribute('href') ?? '')
  expect(target.pathname).toBe('/assets-skills')
  expect(target.searchParams.get('assetId')).toBe('asset-catalog-skill-ppt-builder')
  expect(target.searchParams.get('assetTimeFrom')).toBe('2026-08-01T00:00')
  expect(target.searchParams.get('assetTimeTo')).toBe('2026-10-31T23:59')
  expect(target.searchParams.has('assetVersion')).toBe(false)
  await reportPage.goto(target.href)
  await expect(reportPage.getByLabel('具体资产')).toHaveValue('asset-catalog-skill-ppt-builder')
  await expect(reportPage.getByRole('table', { name: '资产版本表现' })).toBeVisible()
  await expect(reportPage.getByLabel('资产开始时间')).toHaveValue('2026-08-01T00:00')
  await expect(reportPage.getByLabel('资产结束时间')).toHaveValue('2026-10-31T23:59')

  await page.getByLabel('资产搜索').fill('PPT Builder')
  await expect(table.getByRole('row')).toHaveCount(2)
  await table.getByRole('link', { name: 'PPT Builder', exact: true }).click()
  await expect(page.getByRole('table', { name: '资产版本表现' })).toBeVisible()
  await page.goBack()
  await expect(page.getByLabel('具体资产')).toHaveValue('')
  await expect(page.getByLabel('资产搜索')).toHaveValue('PPT Builder')
  await expect(page.getByLabel('资产开始时间')).toHaveValue('2026-08-01T00:00')
  await expect(page.getByLabel('资产结束时间')).toHaveValue('2026-10-31T23:59')
  await expect(table.getByRole('row')).toHaveCount(2)
  await table.getByRole('link', { name: 'PPT Builder', exact: true }).click()
  await expect(page.getByRole('table', { name: '资产版本表现' })).toBeVisible()
  await page.getByRole('button', { name: '返回该类型全部资产' }).click()
  await expect(page.getByLabel('资产搜索')).toHaveValue('PPT Builder')
  await expect(table.getByRole('row')).toHaveCount(2)
  await expect(page.getByLabel('资产开始时间')).toHaveValue('2026-08-01T00:00')

  await page.getByLabel('资产搜索').fill('')
  await page.getByLabel('资产开始时间').fill('2099-01-01T00:00')
  await page.getByLabel('资产结束时间').fill('2099-01-31T23:59')
  await expect(table.getByRole('row')).toHaveCount(5)
  await expect(table.getByRole('cell', { name: '暂无评测结果', exact: true })).toHaveCount(4)
  await expect(page.getByRole('img', { name: '类别产物平均分历史' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '下载报告' })).toBeEnabled()

  // A search that excludes a selected asset switches every surface to the
  // search result scope, including the exported report.
  await page.goto('/assets-skills?assetType=PRODUCTION_SKILL&assetId=asset-catalog-skill-ppt-builder&assetVersion=2.6.0&assetTimeFrom=2026-08-01T00:00&assetTimeTo=2026-10-31T23:59')
  await page.getByLabel('资产搜索').fill('Word Builder')
  await expect(table.getByRole('row')).toHaveCount(2)
  await expect(table.getByRole('link', { name: 'Word Builder', exact: true })).toBeVisible()
  await expect(page.getByRole('table', { name: '资产版本表现' })).toHaveCount(0)
  await expect(page).toHaveURL(url => !url.searchParams.has('assetId') && !url.searchParams.has('assetVersion') && url.searchParams.get('assetQuery') === 'Word Builder')
  const wordDownloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载报告' }).click()
  const wordDownload = await wordDownloadPromise
  const wordPath = await wordDownload.path()
  expect(wordPath).toBeTruthy()
  await reportPage.setContent(await fs.readFile(wordPath!, 'utf8'))
  const wordReport = reportPage.getByRole('table', { name: '分类资产表现' })
  await expect(wordReport.getByRole('row')).toHaveCount(2)
  await expect(wordReport.getByRole('link', { name: 'Word Builder', exact: true })).toBeVisible()
  await expect(wordReport.getByRole('link', { name: 'PPT Builder', exact: true })).toHaveCount(0)
  await expect(reportPage.getByRole('region', { name: '类别总览指标' })).toContainText('资产数1')
  const wordLink = new URL(await wordReport.getByRole('link', { name: 'Word Builder', exact: true }).getAttribute('href') ?? '')
  expect(wordLink.searchParams.get('assetTimeFrom')).toBe('2026-08-01T00:00')
  expect(wordLink.searchParams.get('assetTimeTo')).toBe('2026-10-31T23:59')
})
