import {expect,test,type Page} from '@playwright/test'

const trace='2037904916466732346556'
const moduleScore='module-score-trace-ppt-generate-skill'
const detail=(page:Page)=>page.getByRole('dialog',{name:'skill · 进化详情'})
const record=(page:Page,id:string)=>detail(page).locator(`[data-evolution-record-id="${id}"]`)

test('同模块多归因、同归因两去向、独立准出与待发布',async({page})=>{
  await page.goto(`/cases?traceId=${trace}&caseView=eval&timeRange=30d&environment=Production`)
  await page.getByRole('button',{name:'查看 skill 进化详情',exact:true}).click()
  await detail(page).getByRole('button',{name:'skill sop错误',exact:true}).click()
  const strategy=record(page,'evolution-module-path-demo-sop-strategy'),agent=record(page,'evolution-module-path-demo-sop-agent')
  await expect(strategy).toContainText('等待回传')
  await expect(strategy).not.toContainText('已准出')
  await expect(agent.getByRole('region',{name:'1 是否可进化'})).toContainText('可直接优化')
  await expect(agent.getByRole('region',{name:'3 准出状态'})).toContainText('已准出')
  await expect(agent.getByRole('region',{name:'4 是否上线'})).toContainText('待发布')
  await expect(detail(page)).toContainText('品味库召回错误')
  await expect(detail(page)).toContainText('历史自动版本 / 历史轮次')
  await agent.getByRole('link',{name:'查看进化数据集',exact:true}).click()
  await expect(page).toHaveURL(url=>url.pathname==='/datasets-evaluations' && url.searchParams.get('evolutionRecordId')==='evolution-module-path-demo-sop-agent' && url.searchParams.get('skillVersion')==='2.5.0')
  await expect(page.getByRole('table',{name:'数据集与评测列表'}).getByRole('row')).toHaveCount(6)
  await expect(page.getByRole('table',{name:'数据集与评测列表'})).toContainText('窗口线上数据全集')
  await page.getByRole('button',{name:'SOP 原始归因集A（Mock）',exact:true}).click()
  const dataset=page.getByRole('dialog',{name:'数据集详情 · SOP 原始归因集A（Mock）',exact:true})
  await expect(dataset.getByRole('table',{name:'数据集样本 Trace'}).getByRole('row')).toHaveCount(2)
  await expect(dataset).toContainText(trace)
  await expect(dataset).not.toContainText('2053080938534557768186')
  await page.getByRole('button',{name:'返回来源页面',exact:true}).click()
  await expect(detail(page)).toBeVisible()
  await expect(page).toHaveURL(url=>url.searchParams.get('moduleScoreId')===moduleScore && url.searchParams.get('traceId')===trace && url.searchParams.get('timeRange')==='30d')
  await record(page,'evolution-module-path-demo-sop-agent').getByRole('link',{name:'查看准出评测',exact:true}).click()
  await expect(page.getByRole('dialog',{name:/归因历史详情/})).toContainText('experiment-module-path-demo-window')
  await expect(page.getByRole('dialog',{name:/归因历史详情/})).toContainText('待发布')
  await page.getByRole('button',{name:'返回来源页面',exact:true}).click()
  await expect(detail(page).getByRole('button',{name:'定位治理路径',exact:true})).toHaveCount(0)
})

test('记忆目标使用自身版本与归因，不锁定Skill或借准出',async({page})=>{
  await page.goto(`/cases?traceId=${trace}&caseView=eval&timeRange=30d&environment=Production&skill=skill-ppt-builder`)
  await page.getByRole('button',{name:'查看 记忆 进化详情',exact:true}).click()
  const memory=page.getByRole('dialog',{name:'记忆 · 进化详情'})
  await memory.getByRole('button',{name:'准确率低',exact:true}).click()
  await expect(memory).toContainText('规则待配置')
  await expect(memory).toContainText('memory-policy-demo-v1')
  await memory.getByRole('link',{name:'查看进化数据集',exact:true}).click()
  await expect(page).toHaveURL(url=>url.searchParams.get('governanceObject')==='Memory' && !url.searchParams.has('skill') && !url.searchParams.has('skillCategory') && url.searchParams.get('targetVersion')==='memory-policy-demo-v1')
  await expect(page.getByRole('combobox', {name:'具体治理目标',exact:true})).toHaveValue('memory-policy')
  await expect(page.getByRole('table',{name:'数据集与评测列表'})).toContainText('记忆准确率原始归因集A')
  await expect(page.getByRole('table',{name:'数据集与评测列表'})).not.toContainText('已准出')
  await page.getByRole('button',{name:'返回来源页面',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'记忆 · 进化详情'})).toBeVisible()
})

test('具体过程细项返回、刷新与历史轮次不串评分',async({page})=>{
  await page.goto(`/cases?traceId=${trace}&caseView=eval&timeRange=30d&moduleScoreId=${moduleScore}&evaluationId=process-eval-ppt-recall&processEvaluationId=process-eval-ppt-recall`)
  await expect(detail(page)).toBeVisible()
  await detail(page).getByRole('button',{name:'skill sop错误',exact:true}).click()
  await expect(detail(page)).toContainText('process-eval-ppt-recall')
  await record(page,'evolution-module-path-demo-sop-agent').getByRole('link',{name:'查看进化数据集',exact:true}).click()
  await page.getByRole('button',{name:'返回来源页面',exact:true}).click()
  await expect(detail(page)).toBeVisible()
  await page.reload()
  await expect(detail(page)).toBeVisible()
  await expect(page).toHaveURL(/processEvaluationId=process-eval-ppt-recall/)
  await expect(record(page,'evolution-module-path-demo-sop-agent')).toContainText('待发布')
})

for(const width of [1280,1440])test(`${width}px模块进化表及四阶段详情可读`,async({page},testInfo)=>{
  await page.setViewportSize({width,height:900})
  await page.goto(`/cases?traceId=${trace}&caseView=eval&timeRange=30d`)
  await page.screenshot({path:testInfo.outputPath(`module-matrix-${width}.png`),animations:'disabled'})
  await page.getByRole('button',{name:'查看 skill 进化详情',exact:true}).click()
  await expect(detail(page)).toBeVisible()
  await detail(page).getByRole('button',{name:'skill sop错误',exact:true}).click()
  const overlap=await detail(page).locator('article[data-evolution-record-id="evolution-module-path-demo-sop-agent"] > div.grid > section').evaluateAll(nodes=>{
    const problems:string[]=[]
    for(let i=0;i<nodes.length;i++)for(let j=i+1;j<nodes.length;j++){const a=nodes[i].getBoundingClientRect(),b=nodes[j].getBoundingClientRect();if(Math.min(a.right,b.right)-Math.max(a.left,b.left)>1 && Math.min(a.bottom,b.bottom)-Math.max(a.top,b.top)>1)problems.push(`${i}/${j}`)}return problems
  })
  expect(overlap).toEqual([])
  const clipped=await detail(page).locator('header h2,a,button').evaluateAll(nodes=>nodes.filter(node=>{const el=node as HTMLElement,r=el.getBoundingClientRect();return r.width>0 && r.height>0 && (r.left<0 || r.right>innerWidth+1 || el.scrollWidth>el.clientWidth+1)}).map(node=>node.textContent))
  expect(clipped).toEqual([])
  await record(page,'evolution-module-path-demo-sop-agent').scrollIntoViewIfNeeded()
  await page.screenshot({path:testInfo.outputPath(`module-path-stages-${width}.png`),animations:'disabled'})
  await record(page,'evolution-module-path-demo-sop-agent').getByRole('link',{name:'查看进化数据集',exact:true}).click()
  await page.screenshot({path:testInfo.outputPath(`module-datasets-${width}.png`),animations:'disabled'})
  await page.getByRole('button',{name:'返回来源页面',exact:true}).click()
  await detail(page).getByRole('button',{name:'Close panel',exact:true}).click()
  await page.getByRole('button',{name:'查看 记忆 进化详情',exact:true}).click()
  await page.getByRole('dialog',{name:'记忆 · 进化详情'}).getByRole('button',{name:'准确率低',exact:true}).click()
  await page.getByRole('dialog',{name:'记忆 · 进化详情'}).getByRole('link',{name:'查看进化数据集',exact:true}).click()
  await expect(page.getByRole('combobox',{name:'具体治理目标',exact:true})).toHaveValue('memory-policy')
  await page.screenshot({path:testInfo.outputPath(`module-memory-datasets-${width}.png`),animations:'disabled'})
})
